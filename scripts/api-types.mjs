// Generates src/api/schema.d.ts from the API's OpenAPI document.
//
//   npm run api:types                  reads https://localhost:7187/openapi/v1.json (the API in Development)
//   npm run api:types -- path/to.json  reads a saved document instead
//
// The API's response records are always written whole (a field left out only when the caller may not see
// it, and then it is nullable), but the document marks the fields of init-property records as optional.
// Response schemas are therefore made fully required here; requests and queries keep their optional fields.
import { readFile, writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";

const source = process.argv[2] ?? "https://localhost:7187/openapi/v1.json";

async function load() {
    if (!/^https?:/.test(source)) return JSON.parse(await readFile(source, "utf8"));
    // The development certificate isn't trusted by Node.
    process.env.NODE_TLS_REJECT_UNAUTHORIZED = "0";
    const response = await fetch(source);
    if (!response.ok) throw new Error(`${source} answered ${response.status}. Is the API running in Development?`);
    return response.json();
}

const spec = await load();
for (const [name, schema] of Object.entries(spec.components?.schemas ?? {})) {
    if (/(Request|Query)$/.test(name) || !schema.properties) continue;
    schema.required = Object.keys(schema.properties);
}

const ast = await openapiTS(spec, { alphabetize: true });
const header = "// Generated by `npm run api:types` from the API's OpenAPI document. Do not edit by hand.\n\n";
await writeFile(new URL("../src/api/schema.d.ts", import.meta.url), header + astToString(ast));
console.log(`src/api/schema.d.ts: ${Object.keys(spec.paths).length} paths, ${Object.keys(spec.components.schemas).length} schemas`);
